async function seed() {
  console.log("🚀 Starting Firestore Seeding (26 Government Schemes + Benchmark Applications)...");
  
  // Batches in Firestore support up to 500 writes
  const batch = writeBatch(db);

  for (const s of SCHEMES) {
    const sRef = doc(db, "schemes", s.id);
    batch.set(sRef, s);
    console.log(`  ➕ Queued Scheme: [${s.category.toUpperCase()}] ${s.name}`);
  }

  for (const a of BENCHMARK_APPLICATIONS) {
    const aRef = doc(db, "applications", a.id);
    batch.set(aRef, a);
    console.log(`  ➕ Queued Application: ${a.id} (${a.citizenName} - ${a.schemeName})`);
  }

  const metaRef = doc(db, "meta", "cluster_status");
  batch.set(metaRef, {
    totalSchemes: SCHEMES.length,
    totalApplications: BENCHMARK_APPLICATIONS.length,
    dataCenter: "Gandhinagar State Data Centre (GSDC-Node-01)",
    environment: "production",
    clusterHealth: "optimal",
    loadBalancingStrategy: "round-robin",
    lastSeeded: new Date().toISOString(),
    apiGateway: "https://nagrik-seva-ai.gov.in/api/v1",
  });

  console.log("\n💾 Committing 26 Schemes + Applications batch to Cloud Firestore...");
  await batch.commit();

  console.log("\n🎉 SUCCESS! All 26 Government Schemes & Applications are now 100% LIVE in Cloud Firestore!");
  process.exit(0);
}

seed().catch((e) => {
  console.error("❌ Seeding Error:", e);
  process.exit(1);
});
